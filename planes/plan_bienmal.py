def web(t, s, **kw):
    return {"tipo": "web", "titulo": t, "subtitulo": s, "menu": kw.pop("menu", []), "foto": kw.pop("foto", 0), **kw}


def chat(*g):
    return {"tipo": "chat_grande", "globos": [{"de": d, "texto": t} for d, t in g]}


def res(nombre, est, texto, resp, tit):
    return {"tipo": "resenas", "respuesta_titulo": tit,
            "resenas": [{"nombre": nombre, "estrellas": est, "texto": texto, "respuesta": resp}]}


